void main() {
//    Numeric DT - short, int, byte, long
    byte num1 = 127;
    System.out.println(num1);

    short num2 = 31231;
    System.out.println(num2);

    int num3 = 3213;
    System.out.println(num3);

    long num4 = 6435345;
    System.out.println(num4);

//    Floating DT
    float num5 = 12.45223133123f;
    System.out.println(num5);

    double num6 = 12.45632131232131412;
    System.out.println(num6);

//    char, boolean

    boolean num7 = true;
    System.out.println(num7);

    char num8 = 'a';
    System.out.println((char)(num8 + 2));
}